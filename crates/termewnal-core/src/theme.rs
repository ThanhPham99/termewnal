/// Complete terminal and overlay palette for a [`BuiltinTheme`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ThemePalette {
    pub theme: BuiltinTheme,
    pub is_light: bool,
    pub background: RgbColor,
    pub foreground: RgbColor,
    pub cursor: RgbColor,
    pub selection_bg: RgbColor,
    pub selection_fg: Option<RgbColor>,
    pub match_bg: RgbColor,
    pub match_fg: RgbColor,
    pub active_match_bg: RgbColor,
    pub active_match_fg: RgbColor,
    pub ui_surface: RgbColor,
    pub ui_border: RgbColor,
    pub ui_accent: RgbColor,
    pub ansi: [RgbColor; 16],
}

impl ThemePalette {
    /// Resolves a palette by theme name, defaulting to [`BuiltinTheme::Dark`] when unrecognized.
    pub fn for_name(name: &str) -> Self {
        BuiltinTheme::resolve(name).palette()
    }

    /// Resolves a palette by theme name and applies optional [`ThemeOverrides`].
    pub fn for_name_with_overrides(name: &str, overrides: &ThemeOverrides) -> Self {
        Self::for_name(name).with_overrides(overrides)
    }

    /// Applies valid hex overrides on top of this palette.
    pub fn with_overrides(mut self, overrides: &ThemeOverrides) -> Self {
        if let Some(bg) = overrides.background.as_deref().and_then(RgbColor::from_hex) {
            self.background = bg;
            self.is_light = is_light_rgb(bg);
        }
        if let Some(fg) = overrides.foreground.as_deref().and_then(RgbColor::from_hex) {
            self.foreground = fg;
        }
        if let Some(cur) = overrides.cursor.as_deref().and_then(RgbColor::from_hex) {
            self.cursor = cur;
        }
        if let Some(sel) = overrides.selection_bg.as_deref().and_then(RgbColor::from_hex) {
            self.selection_bg = sel;
        }
        if let Some(acc) = overrides.ui_accent.as_deref().and_then(RgbColor::from_hex) {
            self.ui_accent = acc;
        }
        self
    }
}

const fn is_light_rgb(c: RgbColor) -> bool {
    let luma = (c.r as u32) * 299 + (c.g as u32) * 587 + (c.b as u32) * 114;
    luma >= 128_000
}

const fn rgb(r: u8, g: u8, b: u8) -> RgbColor {
    RgbColor::new(r, g, b)
}

#[allow(clippy::too_many_arguments)]
const fn make_palette(
    theme: BuiltinTheme,
    is_light: bool,
    background: RgbColor,
    foreground: RgbColor,
    cursor: RgbColor,
    selection_bg: RgbColor,
    ui_surface: RgbColor,
    ui_border: RgbColor,
    ui_accent: RgbColor,
    ansi: [RgbColor; 16],
) -> ThemePalette {
    let (match_bg, match_fg, active_match_bg, active_match_fg) = if is_light {
        (
            rgb(0xfe, 0xe8, 0xb0),
            foreground,
            rgb(0xf5, 0x9e, 0x0b),
            rgb(0xff, 0xff, 0xff),
        )
    } else {
        (
            rgb(0x58, 0x4c, 0x2f),
            ansi[11],
            ansi[11],
            background,
        )
    };
    ThemePalette {
        theme,
        is_light,
        background,
        foreground,
        cursor,
        selection_bg,
        selection_fg: None,
        match_bg,
        match_fg,
        active_match_bg,
        active_match_fg,
        ui_surface,
        ui_border,
        ui_accent,
        ansi,
    }
}

