//! Built-in color themes, Tabby community color schemes, and custom palette overrides.

use serde::{Deserialize, Serialize};

/// Lightweight RGB color tuple independent of GUI frameworks.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct RgbColor {
    pub r: u8,
    pub g: u8,
    pub b: u8,
}

impl RgbColor {
    /// Creates an [`RgbColor`] from 8-bit red, green, and blue channels.
    pub const fn new(r: u8, g: u8, b: u8) -> Self {
        Self { r, g, b }
    }

    /// Parses `#RRGGBB` or `RRGGBB` hex colors.
    pub fn from_hex(raw: &str) -> Option<Self> {
        let hex = raw.trim().strip_prefix('#').unwrap_or(raw.trim());
        if hex.len() != 6 {
            return None;
        }
        let r = u8::from_str_radix(&hex[0..2], 16).ok()?;
        let g = u8::from_str_radix(&hex[2..4], 16).ok()?;
        let b = u8::from_str_radix(&hex[4..6], 16).ok()?;
        Some(Self { r, g, b })
    }

    /// Formats this color as `#rrggbb`.
    pub fn to_hex(self) -> String {
        format!("#{:02x}{:02x}{:02x}", self.r, self.g, self.b)
    }
}

/// Optional per-role hex color overrides persisted in `config.toml`.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct ThemeOverrides {
    pub background: Option<String>,
    pub foreground: Option<String>,
    pub cursor: Option<String>,
    pub selection_bg: Option<String>,
    pub ui_accent: Option<String>,
}

impl ThemeOverrides {
    /// Returns `true` when no override colors are set.
    pub fn is_empty(&self) -> bool {
        self.background.is_none()
            && self.foreground.is_none()
            && self.cursor.is_none()
            && self.selection_bg.is_none()
            && self.ui_accent.is_none()
    }
}

